






import os, sys

ENGLISH = "orig/th06e"  
GENERATED = "build/feat"  


def exe_flags(feats):
    if "english" not in feats:
        return []
    generate_english_header()
    return ["/I" + GENERATED.replace("/", "\\")]


def headers():
    return [os.path.join(GENERATED, n) for n in sorted(os.listdir(GENERATED))
            if n.endswith(".h")] if os.path.isdir(GENERATED) else []


def exe_resources(feats):

    return os.path.join(ENGLISH, "th06e.exe") if "english" in feats else None


def generate_english_header():

    src = os.path.join(ENGLISH, "strings.txt")
    if not os.path.exists(src):
        sys.exit(f"{src} is missing: run english.py first")
    out = os.path.join(GENERATED, "english.h")
    os.makedirs(GENERATED, exist_ok=True)
    lines = [b"// Generated by build_hook.py from " + src.encode() + b".", b"#pragma once"]
    with open(src, "rb") as f:
        for line in f.read().splitlines():
            name, _, value = line.partition(b"=")
            literal = value.replace(b"\\", b"\\\\").replace(b'"', b'\\"')
            lines.append(b"#define EN_" + name + b' "' + literal + b'"')
    data = b"\n".join(lines) + b"\n"
    if not os.path.exists(out) or open(out, "rb").read() != data:
        with open(out, "wb") as f:
            f.write(data)
